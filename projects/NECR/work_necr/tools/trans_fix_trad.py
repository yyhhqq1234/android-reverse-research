def fix(path):
    t = io.open(path, encoding='utf-8').read()
    n = 0
    for old, new in PERLINE:
        if old in t:
            t = t.replace(old, new)
            n += 1
    for m in MULTI:
        a, b = m.split('→')
        if a in t:
            t = t.replace(a, b)
            n += 1
    for i in range(0, len(S2T), 2):
        a, b = S2T[i], S2T[i + 1]
        if a in t:
            t = t.replace(a, b)
            n += 1
    io.open(path, 'w', encoding='utf-8', newline='').write(t)
    print(path, 'replacements:', n)


